-- Sigla	Significado	Utilização
--   DF	        Default		Define um valor padrão
--   UQ	        Unique	        Impede valores duplicados
--   CK		Check		Define uma condição que os dados precisam respeitar

-- TABELA: TIPO_COMERCIAL

CREATE TABLE TIPO_COMERCIAL
(
    ID_TIPO_COMERCIAL INT NOT NULL PRIMARY KEY IDENTITY,

    TIPO VARCHAR(50) NOT NULL,

    ATIVO BIT NOT NULL CONSTRAINT DF_TIPO_COMERCIAL_ATIVO DEFAULT 1
)
GO


-- TABELA: TIPO_RESIDENCIAL

CREATE TABLE TIPO_RESIDENCIAL
(
    ID_TIPO_RESIDENCIAL INT NOT NULL PRIMARY KEY IDENTITY,

    TIPO VARCHAR(50) NOT NULL,

    ATIVO BIT NOT NULL CONSTRAINT DF_TIPO_RESIDENCIAL_ATIVO DEFAULT 1
)
GO


-- TABELA: USUARIO

CREATE TABLE USUARIO
(
    ID_USUARIO INT IDENTITY PRIMARY KEY,

    EMAIL VARCHAR(50) NOT NULL CONSTRAINT UQ_USUARIO_EMAIL UNIQUE,

    SENHA VARCHAR(255) NOT NULL
)
GO


-- TABELA: CLIENTE

CREATE TABLE CLIENTE
(
    ID_USUARIO INT NOT NULL PRIMARY KEY REFERENCES USUARIO(ID_USUARIO),

    NOME VARCHAR(50) NOT NULL,

    CPF VARCHAR(14) NOT NULL CONSTRAINT UQ_CLIENTE_CPF UNIQUE,

    TELEFONE VARCHAR(15) NOT NULL,

    STATUS BIT NOT NULL CONSTRAINT DF_CLIENTE_STATUS DEFAULT 1
)
GO


-- TABELA: ADMINISTRADOR

CREATE TABLE ADMINISTRADOR
(
    ID_USUARIO INT NOT NULL PRIMARY KEY REFERENCES USUARIO(ID_USUARIO),

    REGISTRO_CAU VARCHAR(20) NOT NULL CONSTRAINT UQ_ADMINISTRADOR_REGISTRO_CAU UNIQUE
)
GO


-- TABELA: RECUPERACAO DE SENHA

CREATE TABLE RECUPERACAO_SENHA (
    ID_RECUPERACAO INT NOT NULL PRIMARY KEY IDENTITY,

    USUARIO_ID INT NOT NULL REFERENCES USUARIO(ID_USUARIO),

    TOKEN VARCHAR(255) NOT NULL UNIQUE,

    DATA_CRIACAO DATETIME2 NOT NULL DEFAULT SYSDATETIME(),

    DATA_EXPIRACAO DATETIME2 NOT NULL,

    UTILIZADO BIT NOT NULL DEFAULT 0,

    CONSTRAINT CK_RECUPERACAO_EXPIRACAO
        CHECK (DATA_EXPIRACAO > DATA_CRIACAO)
)
GO


-- TABELA: PROJETO

CREATE TABLE PROJETO
(
    ID_PROJETO INT NOT NULL PRIMARY KEY IDENTITY,

    TITULO VARCHAR(30) NOT NULL,

    DESCRICAO VARCHAR(1000) NOT NULL,

    DATA DATETIME NULL,

    STATUS_PUBLICACAO BIT NOT NULL CONSTRAINT DF_PROJETO_PUBLICACAO DEFAULT 1,

    ATIVO BIT NOT NULL CONSTRAINT DF_PROJETO_ATIVO DEFAULT 1,

    CLIENTE_ID INT NULL REFERENCES CLIENTE(ID_USUARIO),

    ADMINISTRADOR_ID INT NOT NULL REFERENCES ADMINISTRADOR(ID_USUARIO),

    TIPO_COMERCIAL_ID INT NULL REFERENCES TIPO_COMERCIAL(ID_TIPO_COMERCIAL),

    TIPO_RESIDENCIAL_ID INT NULL REFERENCES TIPO_RESIDENCIAL(ID_TIPO_RESIDENCIAL),

    ETAPA_ATUAL VARCHAR(30) NOT NULL CONSTRAINT DF_PROJETO_ETAPA DEFAULT 'Não iniciado',

    PORCENTAGEM_CONCLUSAO INT NOT NULL CONSTRAINT DF_PROJETO_PROGRESSO DEFAULT 0,

    CONSTRAINT CK_PROJETO_TIPO CHECK
    (
        (TIPO_COMERCIAL_ID IS NOT NULL
         AND TIPO_RESIDENCIAL_ID IS NULL)

        OR

        (TIPO_COMERCIAL_ID IS NULL
         AND TIPO_RESIDENCIAL_ID IS NOT NULL)
    ),

    CONSTRAINT CK_PROJETO_ETAPA CHECK
    (
        ETAPA_ATUAL IN
        (
            'Não iniciado',
            'Medição',
            'Desenvolvimento do projeto',
            'Apresentação ao cliente',
            'Revisões',
            'Projeto Executivo',
            'Concluído'
        )
    ),

    CONSTRAINT CK_PROJETO_PROGRESSO CHECK
    (
        (ETAPA_ATUAL = 'Não iniciado'
            AND PORCENTAGEM_CONCLUSAO = 0)

        OR (ETAPA_ATUAL = 'Medição'
            AND PORCENTAGEM_CONCLUSAO = 17)

        OR (ETAPA_ATUAL = 'Desenvolvimento do projeto'
            AND PORCENTAGEM_CONCLUSAO = 33)

        OR (ETAPA_ATUAL = 'Apresentação ao cliente'
            AND PORCENTAGEM_CONCLUSAO = 50)

        OR (ETAPA_ATUAL = 'Revisões'
            AND PORCENTAGEM_CONCLUSAO = 67)

        OR (ETAPA_ATUAL = 'Projeto Executivo'
            AND PORCENTAGEM_CONCLUSAO = 83)

        OR (ETAPA_ATUAL = 'Concluído'
            AND PORCENTAGEM_CONCLUSAO = 100)
    )
)
GO


-- TABELA: IMAGEM

CREATE TABLE IMAGEM
(
    ID_IMAGEM INT NOT NULL PRIMARY KEY IDENTITY,

    CAMINHO VARCHAR(500) NOT NULL,

    PROJETO_ID INT NOT NULL REFERENCES PROJETO(ID_PROJETO)
)
GO


-- TABELA: CATEGORIA

CREATE TABLE CATEGORIA
(
    ID_CATEGORIA INT NOT NULL PRIMARY KEY IDENTITY,

    CATEGORIA VARCHAR(50) NOT NULL CONSTRAINT UQ_CATEGORIA_NOME UNIQUE,

    ATIVO BIT NOT NULL CONSTRAINT DF_CATEGORIA_ATIVO DEFAULT 1
)
GO


-- TABELA: PROJETO_CATEGORIA

CREATE TABLE PROJETO_CATEGORIA
(
    PROJETO_ID INT NOT NULL REFERENCES PROJETO(ID_PROJETO),

    CATEGORIA_ID INT NOT NULL REFERENCES CATEGORIA(ID_CATEGORIA),

    PRIMARY KEY (PROJETO_ID, CATEGORIA_ID)
)
GO


-- TABELA: FEEDBACK

CREATE TABLE FEEDBACK
(
    ID_FEEDBACK INT NOT NULL PRIMARY KEY IDENTITY,

    CLIENTE_ID INT NOT NULL REFERENCES CLIENTE(ID_USUARIO),

    PROJETO_ID INT NOT NULL REFERENCES PROJETO(ID_PROJETO),

    NOTA INT NOT NULL,

    COMENTARIO VARCHAR(1000) NOT NULL,

    DATA_ENVIO DATETIME2 NOT NULL CONSTRAINT DF_FEEDBACK_DATA DEFAULT SYSDATETIME(),

    STATUS_APROVACAO VARCHAR(15) NOT NULL CONSTRAINT DF_FEEDBACK_STATUS DEFAULT 'PENDENTE',

    EXIBIR_NOME BIT NOT NULL CONSTRAINT DF_FEEDBACK_EXIBIR_NOME DEFAULT 0,
    -- 1 = exibir nome / 0 = anônimo.

    CONSTRAINT CK_FEEDBACK_NOTA
        CHECK (NOTA BETWEEN 1 AND 5),

    CONSTRAINT CK_FEEDBACK_STATUS
        CHECK
        (
            STATUS_APROVACAO IN
            ('PENDENTE', 'APROVADO', 'REJEITADO')
        )
)
GO




